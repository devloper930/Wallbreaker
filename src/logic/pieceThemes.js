/**
 * Retrieves the style for a player under the selected piece theme
 */
export function getPlayerStyle(playerIndex, themeId = 'gem') {
  const theme = PIECE_THEMES.find(t => t.id === themeId) || PIECE_THEMES[0];
  const safeIdx = Math.max(0, Math.min(theme.players.length - 1, playerIndex ?? 0));
  return theme.players[safeIdx];
}
